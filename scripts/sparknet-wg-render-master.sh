#!/usr/bin/env bash
# Render Master's wg0.conf with one stanza per authorized peer (non-revoked, unexpired).
set -euo pipefail

ROLE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$ROLE_ROOT/scripts/sparknet-master-env.sh" >/dev/null

REG=""
OUT="/dev/stdout"
usage() {
  cat <<'USAGE'
usage: sparknet-wg-render-master.sh --registry <registry.json> [--out <wg0.conf>]
USAGE
}
while [ $# -gt 0 ]; do
  case "$1" in
    --registry) REG="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown arg: $1" >&2; usage; exit 1 ;;
  esac
done
[ -n "$REG" ] || { echo "--registry required" >&2; exit 1; }
[ -f "$REG" ] || { echo "registry not found: $REG" >&2; exit 1; }

STATE_DIR="${SPARKNET_STATE_DIR:?missing}"
OP_PUB="$STATE_DIR/keys/operational.pub.b64"
[ -f "$OP_PUB" ] || { echo "pub missing" >&2; exit 1; }

PY="${PY:-$FABRIC_ROOT/.venv/bin/python}"
[ -x "$PY" ] || PY="$(command -v python3)"
tmp=$(mktemp)
cat > "$tmp.py" <<PYEOF
import sys, json, os
sys.path.insert(0, '${FABRIC_ROOT}')
import importlib.util
spec = importlib.util.spec_from_file_location('authz', '${FABRIC_ROOT}/shared/sparknet-authz.py')
authz = importlib.util.module_from_spec(spec)
sys.modules['authz'] = authz
spec.loader.exec_module(authz)
from pathlib import Path
from datetime import datetime, timezone

reg = json.loads(Path('${REG}').read_text())
pub_b64 = Path('${OP_PUB}').read_text().strip()
pub = authz.public_key_from_b64(pub_b64)
now = datetime.now(timezone.utc)

stanzas = []
for i, entry in enumerate(reg.get('authorizations', [])):
    if entry.get('revoked'):
        continue
    ident = entry.get('identity', {})
    # evaluate
    dec = authz.evaluate(ident, {'authorizations': [entry]}, pub, now=now)
    if not dec.allowed:
        continue
    # enforce /32
    overlay = ident.get('overlay_ipv4', '')
    if '/' not in overlay:
        continue  # skip malformed
    addr, mask = overlay.split('/')
    if mask != '32':
        continue  # must be single peer address
    wg_pub = ident.get('wireguard_public_key_b64')
    if not wg_pub:
        continue
    stanzas.append((addr, wg_pub))

# master own keys if needed? not required by DoD; output minimal config
lines = []
lines.append('# Generated by sparknet-master-wg-render.sh')
lines.append('[Interface]')
lines.append('Address = 10.100.0.1/24')
lines.append('ListenPort = 51820')
lines.append('PrivateKey = # set at runtime')
lines.append('')
for addr, wgpub in sorted(stanzas):
    lines.append(f'[Peer]')
    lines.append(f'PublicKey = {wgpub}')
    lines.append(f'AllowedIPs = {addr}/32')
    lines.append('')
open('${OUT}', 'w').write('\n'.join(lines))
PYEOF
"$PY" "$tmp.py"
