#!/usr/bin/env bash
# Render Master's wg0.conf with one stanza per authorized peer (non-revoked, unexpired).
set -euo pipefail

ROLE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$ROLE_ROOT/scripts/sparknet-master-env.sh" >/dev/null

REG=""
OUT="/dev/stdout"
usage() {
  cat <<'USAGE'
usage: sparknet-wg-render-master.sh --registry <registry.json> [--out <wg0.conf>]
USAGE
}
while [ $# -gt 0 ]; do
  case "$1" in
    --registry) REG="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown arg: $1" >&2; usage; exit 1 ;;
  esac
done
[ -n "$REG" ] || { echo "--registry required" >&2; exit 1; }
[ -f "$REG" ] || { echo "registry not found: $REG" >&2; exit 1; }

STATE_DIR="${SPARKNET_STATE_DIR:?missing}"
OP_PUB="$STATE_DIR/keys/operational.pub.b64"
[ -f "$OP_PUB" ] || { echo "pub missing" >&2; exit 1; }

PY="${PY:-$FABRIC_ROOT/.venv/bin/python}"
[ -x "$PY" ] || PY="$(command -v python3)"

REG_PATH="$REG" OUT_PATH="$OUT" OP_PUB_PATH="$OP_PUB" FABRIC_ROOT="$FABRIC_ROOT" "$PY" - <<'PYEOF'
import importlib.util
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

fabric_root = os.environ["FABRIC_ROOT"]
sys.path.insert(0, fabric_root)
spec = importlib.util.spec_from_file_location("authz", f"{fabric_root}/shared/sparknet-authz.py")
authz = importlib.util.module_from_spec(spec)
sys.modules["authz"] = authz
spec.loader.exec_module(authz)

reg = json.loads(Path(os.environ["REG_PATH"]).read_text())
pub = authz.public_key_from_b64(Path(os.environ["OP_PUB_PATH"]).read_text().strip())
now = datetime.now(timezone.utc)
stanzas = []
for entry in reg.get("authorizations", []):
    if not isinstance(entry, dict) or entry.get("revoked"):
        continue
    ident = entry.get("identity", {})
    if not isinstance(ident, dict):
        continue
    decision = authz.evaluate(ident, {"authorizations": [entry]}, pub, now=now)
    if not decision.allowed:
        continue
    overlay = str(ident.get("overlay_ipv4") or "")
    if "/" not in overlay:
        continue
    addr, mask = overlay.split("/", 1)
    if mask != "32":
        continue
    wg_pub = ident.get("wireguard_public_key_b64")
    if not wg_pub:
        continue
    stanzas.append((addr, wg_pub))

lines = [
    "# Generated by sparknet-master-wg-render.sh",
    "[Interface]",
    "Address = 10.100.0.1/24",
    "ListenPort = 51820",
    "PrivateKey = # set at runtime",
    "",
]
for addr, wgpub in sorted(stanzas):
    lines.extend(["[Peer]", f"PublicKey = {wgpub}", f"AllowedIPs = {addr}/32", ""])
out = Path(os.environ["OUT_PATH"])
if out == Path("/dev/stdout"):
    sys.stdout.write("\n".join(lines))
else:
    out.write_text("\n".join(lines))
PYEOF
